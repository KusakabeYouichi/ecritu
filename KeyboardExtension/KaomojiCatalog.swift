    static let existingEntries: [String] = uniqueOrdered(legacyEntries)

    static let importedEntries: [String] = uniqueOrdered(
        importedCategoryOrder.flatMap { importedEntriesByCategory[$0] ?? [] }
    )

    static let entries: [String] = uniqueOrdered(existingEntries + importedEntries)

    static let allReadings: [String] = importedEntriesByReading.keys.sorted { lhs, rhs in
        lhs.localizedStandardCompare(rhs) == .orderedAscending
    }

    static let readingIndexHeadings: [String] = {
        var headings: [String] = []
        var seen = Set<String>()

        for reading in allReadings {
            guard let first = reading.first else {
                continue
            }

            let heading = String(first)
            if seen.insert(heading).inserted {
                headings.append(heading)
            }
        }

        return headings
    }()

    static func entries(forImportedCategory category: String) -> [String] {
        importedEntriesByCategory[category] ?? []
    }

    static func readings(prefix: String?) -> [String] {
        guard let prefix, !prefix.isEmpty else {
            return allReadings
        }

        return allReadings.filter { $0.hasPrefix(prefix) }
    }

    static func entries(forReading reading: String) -> [String] {
        importedEntriesByReading[reading] ?? []
    }

    private static func uniqueOrdered(_ values: [String]) -> [String] {
        var seen = Set<String>()
        var result: [String] = []
        result.reserveCapacity(values.count)

        for value in values {
            guard seen.insert(value).inserted else {
                continue
            }

            result.append(value)
        }

        return result
    }
